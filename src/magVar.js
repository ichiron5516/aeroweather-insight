/** 年（小数）。例 2026-10-18 → 2026.79 */
export function decimalYear(date = new Date()) {
  const y = date.getUTCFullYear(), a = Date.UTC(y, 0, 1), b = Date.UTC(y + 1, 0, 1);
  return y + (date.getTime() - a) / (b - a);
}

/** 偏角（度、東が正）。lat・lon は度（測地緯度）、altKm は楕円体からの高さ km */
export function declination(lat, lon, year = decimalYear(), altKm = 0) {
  const A = 6378.137, F = 1 / 298.257223563, E2 = F * (2 - F), RE = 6371.2;
  const phi = lat * Math.PI / 180, lam = lon * Math.PI / 180;
  // 測地座標 → 地心座標
  const Rc = A / Math.sqrt(1 - E2 * Math.sin(phi) ** 2);
  const p = (Rc + altKm) * Math.cos(phi), z = (Rc * (1 - E2) + altKm) * Math.sin(phi);
  const r = Math.hypot(p, z), phis = Math.asin(z / r);
  const dt = year - EPOCH;
  const sp = Math.sin(phis), cp = Math.cos(phis);
  // シュミット準正規化ルジャンドル関数 P と dP/dφ
  const P = [], dP = [];
  for (let n = 0; n <= NMAX; n++) { P.push(new Float64Array(n + 1)); dP.push(new Float64Array(n + 1)); }
  P[0][0] = 1; dP[0][0] = 0;
  for (let n = 1; n <= NMAX; n++) {
    for (let m = 0; m <= n; m++) {
      if (n === m) {
        const k = n === 1 ? 1 : Math.sqrt(1 - 1 / (2 * n));
        P[n][m] = k * cp * P[n - 1][m - 1];
        dP[n][m] = k * (cp * dP[n - 1][m - 1] - sp * P[n - 1][m - 1]);
      } else {
        const a = (2 * n - 1) / Math.sqrt(n * n - m * m);
        const b = n - 2 >= m ? Math.sqrt(((n - 1) ** 2 - m * m) / (n * n - m * m)) : 0;
        P[n][m] = a * sp * P[n - 1][m] - (n - 2 >= m ? b * P[n - 2][m] : 0);
        dP[n][m] = a * (sp * dP[n - 1][m] + cp * P[n - 1][m]) - (n - 2 >= m ? b * dP[n - 2][m] : 0);
      }
    }
  }
  let X = 0, Y = 0, Z = 0;
  for (let n = 1; n <= NMAX; n++) {
    const f = (RE / r) ** (n + 2);
    for (let m = 0; m <= n; m++) {
      const gg = g[n][m] + dt * gd[n][m], hh = h[n][m] + dt * hd[n][m];
      const cm = Math.cos(m * lam), sm = Math.sin(m * lam);
      X += -f * (gg * cm + hh * sm) * dP[n][m];
      Y += f * m * (gg * sm - hh * cm) * P[n][m];
      Z -= f * (n + 1) * (gg * cm + hh * sm) * P[n][m];
    }
  }
  Y = cp > 1e-10 ? Y / cp : Y;
  // 地心の北・東 → 測地の北（東はそのまま）
  const psi = phis - phi;
  const Xg = X * Math.cos(psi) - Z * Math.sin(psi);
  return Math.atan2(Y, Xg) * 180 / Math.PI;
}

